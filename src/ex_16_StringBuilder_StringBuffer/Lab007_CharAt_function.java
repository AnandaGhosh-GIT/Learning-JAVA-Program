package ex_16_StringBuilder_StringBuffer;

public class Lab007_CharAt_function {
    public static void main(String[] args) {
        StringBuffer sB = new StringBuffer("Ananda");

        //// charAt() method is a built-in function of the String class that
        //// returns the character at a specific index (position) within a string.
        System.out.println(sB.charAt(3));
    }
}
